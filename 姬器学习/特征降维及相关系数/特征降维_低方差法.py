"""
案例:
    筛选垃圾邮箱的字典.

回顾: 机器学习开发流程.
    1. 读取数据.
    2. 数据的预处理.
    3. 特征工程.
        特征提取, 特征预处理(归一化, 标准化), 特征降维, 特征提取, 特征组合.
    4. 模型训练.
    5. 模型预测.
    6. 模型评估.

特征降维:
    概述/目的:
        减少特征, 用来降低模型出现过拟合的情况(降低风险)
    思路:
        低方差法, 会设置一个方差阈值, 小于该阈值的列, 都会被删除掉, 只保留区别较大的字段, 更容易分析出结果.

低方差法快速复习:
    1. 它看的是单个特征列自己的波动程度, 不看标签 y.
    2. 如果一列数据几乎所有样本都一样, 方差就很小, 通常说明它区分样本的能力弱.
    3. 适合高维稀疏数据的初步过滤, 例如:
        - 垃圾邮件/新闻分类中的词袋特征.
        - 基因表达数据中几乎不变化的基因.
        - 推荐系统/用户画像中几乎全为0或全为1的字段.
    4. 它属于 特征选择: 保留的还是原始特征中的一部分.

公式:
    Var(X) = sum((xi - mean(X)) ** 2) / n

二值特征补充:
    如果某列只有0和1, 且1出现的比例为p, 方差为:
        Var(X) = p * (1 - p)
    例如某个词只在1%的邮件中出现:
        Var = 0.01 * 0.99 = 0.0099

超参:
    threshold:
        方差 <= threshold 的列会被删除.
        方差 > threshold 的列会被保留.
    常用选择:
        threshold=0: 只删除完全不变的常量列.
        threshold=0.01 * 0.99: 删除出现比例低于1%或高于99%的二值特征.
        threshold=0.05 * 0.95: 删除出现比例低于5%或高于95%的二值特征.

注意:
    低方差法不代表方差小的特征一定没用, 它只是一个简单、快速的粗筛方法.
"""

# 导包.
from sklearn.feature_selection import VarianceThreshold
import pandas as pd


# 1. 读取数据, 查看维度.
df = pd.read_csv('../朴素贝叶斯/data/垃圾邮件分类数据.csv')
print(df.shape) # (971, 25734)  -> (行, 列)

# 2. 创建 低方差对象.
transfer = VarianceThreshold(threshold=1)
# 3. 处理特征, 筛选出方差大于 threshold 的列.
x_new = transfer.fit_transform(df)

# 4. 打印处理后的 维度.
print(x_new.shape)  # (971, 144)  -> (行, 列)

# 5. 补充: 查看哪些列被保留下来, 方便理解它不是生成新特征, 而是筛选原特征.
# get_support() 会返回布尔数组: True 表示该列被保留, False 表示该列被删除.
selected_columns = df.columns[transfer.get_support()]
print(f'保留下来的特征数量: {len(selected_columns)}')
print(f'前10个保留下来的特征名: {list(selected_columns[:10])}')
